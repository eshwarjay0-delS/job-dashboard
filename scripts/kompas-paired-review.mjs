/**
 * Pair independently captured ChatGPT reference answers with verified Kompas
 * capture records. This is an evidence-completeness check, never an AI grader.
 * The source fingerprint is a provenance check, not a proof the candidate's
 * resume statements or generated answers are true.
 */
import { readFile, mkdir, writeFile, unlink } from "node:fs/promises"
import { readFileSync } from "node:fs"
import { createHash } from "node:crypto"
import { dirname, resolve, sep } from "node:path"
import { fileURLToPath } from "node:url"
import { fixtureName } from "./lib/evaluation-fixtures.mjs"

const ID = /^[A-Za-z0-9][A-Za-z0-9_-]{0,99}$/
const SHA = /^[a-f0-9]{64}$/
function canonicalFixture(name) {
  // Never resolve a caller-supplied path; only audited fixtures are valid.
  const safe = fixtureName(name)
  const bytes = readFileSync(new URL("./fixtures/kompas-evaluation/" + safe + ".json", import.meta.url))
  const digest = createHash("sha256").update(bytes).digest("hex")
  const rows = JSON.parse(bytes.toString("utf8"))
  return { digest, byId: listUnique(rows, "canonical fixture"), count: rows.length }
}
function check(ok, message) { if (!ok) throw new Error(message) }
function listUnique(rows, label) {
  check(Array.isArray(rows), label + " must be an array")
  const byId = new Map()
  for (const row of rows) {
    check(row && ID.test(String(row.id || "")), label + " has an invalid case id")
    check(!byId.has(row.id), label + " has duplicate id " + row.id)
    byId.set(row.id, row)
  }
  return byId
}
function words(text) { return String(text || "").trim().split(/\s+/).filter(Boolean).length }

/**
 * The manifest is recorded by the live capture runner. It cannot prove that
 * a third-party reference export was really generated by ChatGPT, or that a
 * human reviewer has verified the content.
 */
export function pairCapturedAnswers(captures, manifest, reference, expectedCount = 50) {
  check(Number.isSafeInteger(expectedCount) && expectedCount > 0, "Invalid expected case count")
  check(manifest && manifest.status === "capture-complete", "A successful capture-complete manifest is required")
  check(manifest.quality === "unverified", "Unexpected quality state; preserve the original unverified capture")
  check(manifest.caseCount === expectedCount && manifest.capturedCount === expectedCount, "Manifest is not a complete " + expectedCount + "-case capture")
  check(SHA.test(String(manifest.sourcesSha256 || "")), "Missing sources SHA-256 in capture manifest")
  check(typeof manifest.fixture === "string" && manifest.fixture.trim(), "Missing source fixture")
  const authoritative = canonicalFixture(manifest.fixture)
  check(authoritative.count === expectedCount, "Expected count differs from canonical fixture")
  check(manifest.fixtureSha256 === authoritative.digest, "Manifest fixture SHA-256 does not match the repository fixture")
  check(reference?.fixtureSha256 === authoritative.digest, "Reference fixture SHA-256 does not match the repository fixture")
  const cases = listUnique(manifest.cases, "manifest cases")
  const captured = listUnique(captures, "Kompas captures")
  check(cases.size === expectedCount && captured.size === expectedCount, "Incomplete Kompas capture cases")
  check(reference && SHA.test(String(reference.sourcesSha256 || "")), "Reference export must identify the exact source-bundle SHA-256")
  check(reference.sourcesSha256 === manifest.sourcesSha256, "Reference and Kompas source bundles are different")
  const benchmark = listUnique(reference.responses, "reference responses")
  check(benchmark.size === expectedCount, "Incomplete ChatGPT reference cases")
  const pairs = []
  for (const manifestCase of manifest.cases) {
    const id = manifestCase.id
    const capture = captured.get(id)
    const ref = benchmark.get(id)
    const original = authoritative.byId.get(id)
    check(!!original, "Unrecognized case ID in manifest: " + id)
    check(!!capture && !!ref, "Unpaired case " + id)
    check(manifestCase.captureId === capture.captureId && typeof capture.captureId === "string" && capture.captureId.length > 10, "Capture ID differs from manifest at " + id)
    check(manifestCase.reviewStatus === "pending", "Capture has an unexpected review state at " + id)
    check(typeof capture.question === "string" && capture.question.trim() && capture.question === ref.question, "Questions differ at " + id)
    check(capture.question === original.question, "Question differs from canonical fixture at " + id)
    check(typeof capture.text === "string" && capture.text.trim(), "Missing actual Kompas answer at " + id)
    check(typeof ref.text === "string" && ref.text.trim(), "Missing ChatGPT reference answer at " + id)
    check(capture.status !== "failed" && capture.degraded !== true, "Degraded or failed Kompas capture at " + id)
    check(capture.review && capture.review.status === "pending", "Kompas capture was not marked pending review at " + id)
    check(capture.provenance?.sourcesSha256 === manifest.sourcesSha256, "Kompas source fingerprint mismatch at " + id)
    check(capture.provenance?.fixtureSha256 === authoritative.digest, "Kompas fixture fingerprint mismatch at " + id)
    check(capture.fixture === manifest.fixture, "Kompas fixture mismatch at " + id)
    check(typeof capture.meta?.model === "string" && capture.meta.model.trim() && !/mock|synthetic|fake/i.test(capture.meta.model), "Missing or synthetic Kompas model at " + id)
    check(typeof capture.meta?.provider === "string" && capture.meta.provider.trim() && !/mock|synthetic|fake/i.test(capture.meta.provider), "Missing or synthetic Kompas provider at " + id)
    check(manifestCase.model === capture.meta.model, "Model metadata differs from manifest at " + id)
    pairs.push({
      id, question: capture.question, reference: ref.text, kompas: capture.text,
      referenceModel: typeof ref.model === "string" ? ref.model : "unverified",
      kompasModel: capture.meta.model, kompasProvider: capture.meta.provider,
      referenceWords: words(ref.text), kompasWords: words(capture.text),
      humanReview: "pending",
    })
  }
  const avg = key => Math.round(pairs.reduce((sum, p) => sum + p[key], 0) / pairs.length)
  return {
    fixture: manifest.fixture, fixtureSha256: authoritative.digest, sourceSha256: manifest.sourcesSha256,
    count: pairs.length, referenceCount: benchmark.size, kompasCount: captured.size,
    averageReferenceWords: avg("referenceWords"), averageKompasWords: avg("kompasWords"),
    quality: "unverified", reviewedByHuman: 0,
    caveat: "Pairs and source hashes match, but provider claims are not independently authenticated. No semantic correctness, factual grounding, spoken quality, or human preference score has been verified.",
    pairs,
  }
}
function cell(text) {
  return String(text || "").replace(/&/g, "&amp;").replace(/</g, "&lt;")
    .replace(/>/g, "&gt;").replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>")
}
export function renderPairedMarkdown(report) {
  const lines = [
    "# Kompas versus ChatGPT — original answers, paired by case ID",
    "",
    "Cases with both original outputs: " + report.count,
    "Fixture: " + report.fixture,
    "Shared source SHA-256: " + report.sourceSha256,
    "Canonical question fixture SHA-256: " + report.fixtureSha256,
    "Average reference words: " + report.averageReferenceWords,
    "Average Kompas words: " + report.averageKompasWords,
    "",
    "**Human-reviewed quality: NOT VERIFIED (0/" + report.count + ").**",
    "",
    report.caveat,
    "",
    "| Case | Exact question | ChatGPT reference (original) | Kompas (original) | Models |",
    "|---|---|---|---|---|",
  ]
  for (const p of report.pairs)
    lines.push("| " + cell(p.id) + " | " + cell(p.question) + " | " + cell(p.reference) +
      " | " + cell(p.kompas) + " | " + cell(p.referenceModel) + " / " + cell(p.kompasModel) + " |")
  lines.push("", "## Independent review required",
    "For every case, separately grade answer relevance, explicit requirements, factual evidence, technical accuracy, context continuity, unnecessary material, natural delivery and latency. Explain each failure with cited answer text. Do not mark this table as 50/50 quality passed without that review.",
    "")
  return lines.join("\n")
}
export async function runCli(args) {
  check(args.length === 4, "Usage: node scripts/kompas-paired-review.mjs PRIVATE_CAPTURE.json PRIVATE_MANIFEST.json PRIVATE_REFERENCE.json PRIVATE_OUTPUT.md")
  const [capturePath, manifestPath, referencePath, destination] = args
  // Do not write potentially sensitive reference/candidate answers inside a repo.
  const root = resolve(fileURLToPath(new URL("../", import.meta.url)))
  const target = resolve(destination)
  const jsonTarget = target.toLowerCase().endsWith(".md") ? target.slice(0, -3) + ".json" : target + ".json"
  check(target !== jsonTarget && target !== root && !target.startsWith(root + sep) &&
    jsonTarget !== root && !jsonTarget.startsWith(root + sep), "Paired responses must be written outside the repository")
  const [captures, manifest, reference] = await Promise.all([
    readFile(capturePath, "utf8").then(JSON.parse),
    readFile(manifestPath, "utf8").then(JSON.parse),
    readFile(referencePath, "utf8").then(JSON.parse),
  ])
  const report = pairCapturedAnswers(captures, manifest, reference)
  await mkdir(dirname(target), { recursive: true, mode: 0o700 })
  await mkdir(dirname(jsonTarget), { recursive: true, mode: 0o700 })
  // Both private formats are required: Markdown to compare visually, JSON to
  // review every case. A failed second write must not leave a partial pair.
  await writeFile(jsonTarget, JSON.stringify(report, null, 2) + "\n", { flag: "wx", mode: 0o600 })
  try {
    await writeFile(target, renderPairedMarkdown(report), { flag: "wx", mode: 0o600 })
  } catch (error) {
    await unlink(jsonTarget).catch(() => {})
    throw error
  }
  return { saved: target, structured: jsonTarget, paired: report.count, quality: report.quality }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  runCli(process.argv.slice(2)).then(x => console.log(JSON.stringify(x)))
    .catch(e => { console.error(e.message); process.exitCode = 1 })
}
