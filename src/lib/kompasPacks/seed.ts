import type { KompasPack, PackKind } from "./types.ts"

/**
 * Seeded Role and Category subjects.
 * Topics from the owner's list, the Kompas question families in
 * src/lib/kompasQuestionFamilies.ts, and the leaf names on
 * origin/ops/second-bot-packs (docs/kompas-packs). That branch's copy is the
 * Fortinet AWS persona, so none of its stories, employers, or tool claims
 * are copied. ops/chief-packs is not on origin. Stories stay inside Citi Bank,
 * CVS Health, the City of San Diego, Charter Communications, and Accenture.
 */

type Spec = {
  id: string
  kind: PackKind
  title: string
  blurb: string
  focus: string
  tools: string[]
  playbook: string
  metrics: string
  beats: [string, string, string]
  avoid: string[]
  bankQ?: string
}

function buildPack(spec: Spec): KompasPack {
  const tools = spec.tools.join(", ")
  const dossier = [
    `${spec.focus} The tools I use are ${tools}.`,
    `Playbook: ${spec.playbook} Metrics I report: ${spec.metrics.replace(/\.$/, "")}.`,
    spec.beats.join(" "),
  ].join("\n\n")
  const probes = [
    { question: `Walk me through the last time you did ${spec.title} work.`, answer: spec.beats[0] },
    { question: "What do you measure, and who gets the ticket?", answer: `I measure ${spec.metrics} ${spec.beats[1]}` },
    { question: spec.bankQ || "What do you do when the first check is not enough?", answer: spec.beats[2] },
  ]
  return {
    id: spec.id,
    kind: spec.kind,
    title: spec.title,
    blurb: spec.blurb,
    dossier,
    mustMention: spec.tools.slice(0, 8),
    avoid: spec.avoid,
    probes,
    checklist: [
      { item: "Tools", brief: `Name ${tools} only when the question needs them.` },
      { item: "Playbook", brief: spec.playbook },
      { item: "Metrics", brief: spec.metrics },
      { item: "Citi story", brief: spec.beats[0] },
      { item: "Second story", brief: spec.beats[1] },
    ],
    notebookLmUrl: "",
  }
}

