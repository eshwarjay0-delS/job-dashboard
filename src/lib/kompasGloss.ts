const EXPERIENCE = /\b(?:I (?:worked|spent|started my career)|at Citi\b|at Cigna\b|four years|three years|Cincinnati|unloader)\b/i

export function glossFor(term: string): { glossed: true; gloss: Gloss } | { glossed: false; unglossed: true } {
  const key = String(term || "").toLowerCase().replace(/[^a-z0-9]+/g, "")
  const gloss = GLOSSES[key] || Object.values(GLOSSES).find((item) => item.term.toLowerCase().replace(/[^a-z0-9]+/g, "") === key)
  return gloss ? { glossed: true, gloss } : { glossed: false, unglossed: true }
}

export type StatementCheck = { ok: boolean; line: string; reason: string }

/** Block or replace a line that contradicts a gloss or asserts unsupported experience. Unsure lines stay. */
export function validateStatement(line: string, resume = ""): StatementCheck {
  const text = String(line || "").replace(/\s+/g, " ").trim()
  if (!text) return { ok: true, line: "", reason: "" }
  const corpus = String(resume || "").toLowerCase()
  const claimed = text.match(EXPERIENCE)
  if (claimed) {
    const phrase = claimed[0].toLowerCase()
    const distinctive = phrase.replace(/^(?:i |at )/, "").trim()
    if (!corpus.includes(phrase) && !(distinctive && corpus.includes(distinctive))) {
      return { ok: false, line: "", reason: "experience is not in the resume" }
    }
  }
  for (const gloss of Object.values(GLOSSES)) {
    if (!gloss.wrong.some((pattern) => pattern.test(text))) continue
    return { ok: false, line: gloss.order, reason: `${gloss.term} contradicts its gloss` }
  }
  return { ok: true, line: text, reason: "" }
}

export function validateLines(lines: string[], resume = ""): string[] {
  const out: string[] = []
  for (const line of lines) {
    const check = validateStatement(line, resume)
    if (!check.ok && !check.line) continue
    const kept = check.ok ? line : check.line
    if (kept && !out.includes(kept)) out.push(kept)
  }
  return out
}
